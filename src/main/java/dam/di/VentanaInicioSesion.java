    private void btnEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntrarActionPerformed
        String usuario = txtUsuario.getText().trim();
        String contrasena = new String(txtContrasena.getPassword());
        
        if (usuario.isEmpty() || contrasena.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Introduce todos los campos",
            "Faltan datos", JOptionPane.WARNING_MESSAGE);
        } else if (usuario.equals(USUARIO) && contrasena.equals(CONTRASENA)) {
            new PrimeraVentana().setVisible(true); // abre la principal
            dispose(); // y cierra esta
        } else {
            JOptionPane.showMessageDialog(this, "El usuario o la contraseña no son correctos.",
                "No se puede entrar", JOptionPane.ERROR_MESSAGE);
            txtContrasena.setText(""); // borra la contraseña
            txtContrasena.requestFocusInWindow(); // y deja el cursor en ella
}
    }//GEN-LAST:event_btnEntrarActionPerformed

